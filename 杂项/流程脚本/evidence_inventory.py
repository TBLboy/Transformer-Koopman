import hashlib
import json
import sqlite3
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

DB = (r'D:\Project\vibe-coding\.project-log\.state\c15166f6f14948aa85604021638f0b1a'
      r'\2428c28d612809201bbb0fec8029f394b8ca9a64ea9618cfc5ecc99617f72274\state.sqlite3')
root = Path(r'D:\Project\vibe-coding')
conn = sqlite3.connect('file:' + DB + '?mode=ro', uri=True)


def rows(table):
    cols = [r[1] for r in conn.execute('pragma table_info(%s)' % table)]
    return [dict(zip(cols, r)) for r in conn.execute('select * from %s' % table)]


evidence = rows('evidence')
goals = rows('goals')
tasks = rows('tasks')

print('=== goals ===')
active = []
for g in goals:
    req = g.get('required_evidence')
    try:
        req = json.loads(req) if isinstance(req, str) else req
    except Exception:
        req = None
    print('  ', g['id'], '|', g.get('status'), '| required_evidence:', req)
    if g.get('status') == 'active':
        active.append(g)
print('active goals:', [g['id'] for g in active])
print('current active goal id:', [t['id'] for t in tasks if t.get('status') == 'in-progress'])

# classification
buckets = Counter()
detail = {}
for e in evidence:
    vb = e.get('version_binding') or '{}'
    try:
        vb = json.loads(vb)
    except Exception:
        vb = {}
    fh = vb.get('file_hashes') or {}
    if not fh:
        buckets['no-selectors'] += 1
        detail[e['id']] = 'no-selectors'
        continue
    kinds = set()
    for f, rec in fh.items():
        p = root / f
        if not p.exists():
            kinds.add('missing')
            continue
        b = p.read_bytes()
        if hashlib.sha256(b).hexdigest() == rec:
            kinds.add('match')
        elif hashlib.sha256(b.replace(b'\r\n', b'\n')).hexdigest() == rec:
            kinds.add('eol-only')
        else:
            kinds.add('changed')
    if kinds <= {'match', 'eol-only'}:
        cls = 'applicable'      # every covered file still matches (EOL-only counts as unchanged)
    elif 'missing' in kinds:
        cls = 'missing-input'
    else:
        cls = 'changed-input'
    buckets[cls] += 1
    detail[e['id']] = cls

print()
print('=== status x classification ===')
combo = Counter()
for e in evidence:
    combo[(e.get('status'), detail[e['id']])] += 1
for key in sorted(combo, key=lambda k: (str(k[0]), str(k[1]))):
    print('  %-16s %-16s %d' % (key[0], key[1], combo[key]))

# which required evidence of any goal is stale / non-current
print()
print('=== goal required evidence state ===')
ev_state = {e['id']: e.get('status') for e in evidence}
for g in goals:
    req = g.get('required_evidence')
    try:
        req = json.loads(req) if isinstance(req, str) else req
    except Exception:
        req = None
    if not req:
        continue
    missing = [r for r in req if r not in ev_state]
    stale = [r for r in req if ev_state.get(r) in ('stale', 'invalid')]
    print('  %-10s status=%-9s req=%d missing=%s stale=%s' % (g['id'], g.get('status'), len(req), missing, stale))

